function normalizeMediaAsset(assetKey, asset) {
  const provenanceStatus = asset.provenanceStatus || 'needs-review';
  return {
    ...LOCAL_ARCHIVE_PROVENANCE,
    ...asset,
    provenanceStatus,
    credit: provenanceStatus === 'verified'
      ? asset.credit
      : 'Local archive image - provenance review needed',
    assetKey,
  };
}

